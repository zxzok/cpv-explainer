def summarise(rows: list[dict]) -> list[dict]:
    keys = ["ceiling_error_selected", "ceiling_error_reference", "ceiling_error_uniform",
            "ceiling_signed_selected", "design_regret", "design_regret_exhaustive",
            "ridge_r2_selected", "ridge_r2_oracle", "ridge_loss_selected",
            "ridge_regret", "tau_hat", "I_true_selected", "I_fit_selected",
            "I_true_star"]
    out = []
    for arm in ARMS:
        for lname in LABELS:
            sub = [r for r in rows if r["arm"] == arm.key and r["label"] == lname]
            rec = {"arm": arm.key, "display": arm.display, "group": arm.group,
                   "label": lname, "n_rep": len(sub)}
            for k in keys:
                v = np.array([r[k] for r in sub], dtype=float)
                v = v[np.isfinite(v)]
                if v.size == 0:
                    rec[f"{k}_mean"] = rec[f"{k}_se"] = float("nan")
                    continue
                rec[f"{k}_mean"] = float(v.mean())
                rec[f"{k}_se"] = float(v.std(ddof=1) / np.sqrt(v.size)) if v.size > 1 \
                    else 0.0
            positive_regret = np.array(
                [float(r["design_regret"]) > OPTIMALITY_TOL for r in sub], dtype=float)
            selection_error = positive_regret.copy()
            for name, values in (("selection_error", selection_error),
                                 ("positive_regret", positive_regret)):
                rate = float(values.mean())
                rec[f"{name}_rate"] = rate
                rec[f"{name}_se"] = float(np.sqrt(rate * (1.0 - rate) / len(values)))
            mode = {}
            for r in sub:
                mode[r["protocol_selected"]] = mode.get(r["protocol_selected"], 0) + 1
            rec["modal_protocol"] = max(mode, key=mode.get)
            rec["modal_protocol_frac"] = max(mode.values()) / len(sub)
            out.append(rec)
    return out


def make_figure(summary: list[dict]) -> None:
    plt = setup_matplotlib()

    def val(arm_key: str, lname: str, field_: str) -> float:
        return [s[field_] for s in summary
                if s["arm"] == arm_key and s["label"] == lname][0]

    def avg(arm_key: str, field_: str) -> float:
        return float(np.mean([val(arm_key, ln, field_) for ln in LABELS]))

    # Rows are sorted by design regret, ties broken by ceiling error.
    arms_sorted = sorted(ARMS, key=lambda a: (avg(a.key, "design_regret_mean"),
                                              avg(a.key, "ceiling_error_selected_mean")))
    y = np.arange(len(arms_sorted))
    y_ctrl = float(y[[a.key for a in arms_sorted].index("control")])
    offs = {"mean": 0.18, "occupation": -0.18}
    style = {"mean": dict(color=PALETTE[0], marker="o"),
             "occupation": dict(color=PALETTE[1], marker="s")}

    fig, axes = plt.subplots(1, 2, figsize=(7.0, 4.3), sharey=True,
                             gridspec_kw=dict(wspace=0.08))
    panels = [("ceiling_error_selected",
               r"ceiling error  $|\hat{I}_g(\hat{S}) - I_g(\hat{S})|$"),
              ("design_regret",
               r"design regret  $I_g(S^\star) - I_g(\hat{S})$")]
    for ax, (field_, xlabel) in zip(axes, panels):
        first = field_ == panels[0][0]
        ax.axhspan(y_ctrl - 0.5, y_ctrl + 0.5, color="0.88", lw=0, zorder=0)
        ax.axvline(avg("control", f"{field_}_mean"), color="0.35", ls="--", lw=0.9,
                   zorder=1, label="correctly specified control" if first else None)
        for lname in LABELS:
            m = np.array([val(a.key, lname, f"{field_}_mean") for a in arms_sorted])
            e = np.array([val(a.key, lname, f"{field_}_se") for a in arms_sorted])
            for yy, mm in zip(y + offs[lname], m):
                ax.plot([0.0, mm], [yy, yy], color=style[lname]["color"], lw=0.9,
                        alpha=0.4, zorder=2, solid_capstyle="butt")
            ax.errorbar(m, y + offs[lname], xerr=1.96 * e, ls="none", elinewidth=0.9,
                        capsize=1.6, ms=4.2, mew=0.0, zorder=3,
                        label=f"{lname} label" if first else None, **style[lname])
        ax.set_xlabel(xlabel)
        ax.set_xlim(left=0.0)
        ax.grid(axis="y", visible=False)
        ax.margins(x=0.06)

    axes[0].set_yticks(y)
    axes[0].set_yticklabels([a.display for a in arms_sorted])
    for tick, a in zip(axes[0].get_yticklabels(), arms_sorted):
        if a.key == "control":
            tick.set_fontweight("bold")
    axes[0].set_ylim(-0.6, len(arms_sorted) - 0.4)
    axes[0].legend(loc="lower right")
    fig.tight_layout()
    save_figure(fig, "fig_misspecification")
    plt.close(fig)


