"""Experiment S6 -- model misspecification.

Every arm follows the same three-stage pipeline.

    (1) TRUTH        data are generated by a true model  (kernel, calibration links,
                     subject heterogeneity, missingness mechanism, label noise);
    (2) FIT          an analyst who believes a *wrong* model estimates a
                     covariance ``K_hat`` from ``m`` dense calibration
                     trajectories, reports the plug-in ceiling ``I_fit`` and
                     selects a protocol ``S_fit`` with the label-aware design
                     algorithm of the paper;
    (3) EVALUATE     the reported ceiling and the selected protocol are scored
                     under the TRUE model.

Three numbers are recorded per arm.

    ceiling error    |I_fit(S_fit) - I_true(S_fit)|        (is the report honest?)
    design regret    I_true(S*_true) - I_true(S_fit)       (is the design good?)
    downstream loss  1 - R^2 of a ridge predictor trained under S_fit on data
                     from the true model, plus its regret against S*_true.

The analyst's model is always a *single shared stationary OU kernel* whose
integral time is fitted by least squares to the empirical lag-correlation
profile, with the label weights (known by construction, they define the target)
and the measurement model taken as given.  The correctly specified control arm
(OU -> OU) therefore exposes the floor: finite-``m`` estimation error plus the
1-swap suboptimality of the greedy design algorithm.

Design geometry.  The label is *recency weighted* (half-life ``T/2.5``) and the
12-action candidate set is heterogeneous: eight *irregularly spaced* admissible
occasions, denser towards the end of the horizon, plus ``M = 2`` and ``M = 4``
replicated occasions that cost proportionally more.  All three choices are
deliberate.  With a stationary kernel, uniform label weights and equally spaced
candidates the design problem is translation symmetric, every model returns the
same spread placement, and design regret is identically zero for reasons that
have nothing to do with misspecification.  Recency weighting, irregular times
and a distinct-occasions / repeated-segments trade-off together make the optimal
protocol genuinely depend on the correlation time -- exactly the quantity a
misspecified model gets wrong.

The calibration-link arms isolate covariance-estimation sensitivity. The
latent target and deployed point-observation model remain functions of the
Gaussian ``Z`` process, while the dense calibration trajectories supplied to
the analyst are coordinatewise monotone transforms of ``Z``. Thus the
occupation threshold ``c=0`` is applied to ``Z`` and is non-degenerate; it is
never applied to an uncentred positive lognormal variable. Rank normalisation
recovers the latent Gaussian copula, whereas Pearson correlation of the
distorted calibration values generally does not.
"""

