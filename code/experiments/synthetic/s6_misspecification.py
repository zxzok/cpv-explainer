# Label transforms of the *target* (arms 11 and 12)
# --------------------------------------------------------------------------
def quantise(theta: Array, label_name: str, var_theta: float) -> Array:
    """``Q(Theta)``: five equally spaced levels covering the bulk of the label."""
    if label_name == "mean":
        d = np.sqrt(var_theta)
        return np.clip(np.round(theta / d), -2.0, 2.0) * d
    return np.round(np.clip(theta, 0.0, 1.0) / 0.25) * 0.25


def quantised_mean_stats(V: float, F: Array, n_nodes: int = 120) -> Array:
    """Exact ``Var{E(Q(Theta) | Y_S)}`` for the (Gaussian) mean label.

    ``(Theta, Y_S)`` is jointly Gaussian, so ``Theta`` is independent of ``Y_S``
    given the posterior mean ``mu = E(Theta | Y_S) ~ N(0, F)`` and
    ``Theta | mu ~ N(mu, V - F)``.  Both the inner conditional expectation and
    the outer variance are then one-dimensional Gaussian integrals.
    """
    d = np.sqrt(V)
    levels = np.array([-2.0, -1.0, 0.0, 1.0, 2.0]) * d
    edges = np.array([-1.5, -0.5, 0.5, 1.5]) * d
    x, w = roots_hermitenorm(n_nodes)
    pw = w / np.sqrt(2.0 * np.pi)
    out = np.empty(F.shape[0])
    for i, Fi in enumerate(F):
        s = np.sqrt(max(V - Fi, 1e-12))
        mu = np.sqrt(max(Fi, 0.0)) * x
        cdf = np.concatenate([np.zeros((mu.size, 1)),
                              ndtr((edges[None, :] - mu[:, None]) / s),
                              np.ones((mu.size, 1))], axis=1)
        h = np.diff(cdf, axis=1) @ levels
        out[i] = float(pw @ (h * h) - (pw @ h) ** 2)
    return out


def quantised_var_total(V: float, label_name: str, rng: np.random.Generator,
                        K: Array, label: LabelFunctional) -> float:
    """``Var Q(Theta)``: exact for the mean label, Monte Carlo for the occupation label."""
    if label_name == "mean":
        d = np.sqrt(V)
        levels = np.array([-2.0, -1.0, 0.0, 1.0, 2.0]) * d
        edges = np.array([-1.5, -0.5, 0.5, 1.5]) * d
        pr = np.diff(np.concatenate([[0.0], ndtr(edges / np.sqrt(V)), [1.0]]))
        return float(pr @ (levels**2) - (pr @ levels) ** 2)
    L = np.linalg.cholesky(K + 1e-10 * np.eye(P_GRID))
    tot, tot2, n = 0.0, 0.0, 0
    for _ in range(MC_VAR // 20_000):
        Z = rng.standard_normal((20_000, P_GRID)) @ L.T
        q = quantise(label.apply(Z) @ OMEGA, label_name, V)
        tot += q.sum()
        tot2 += (q * q).sum()
        n += q.size
    return float(tot2 / n - (tot / n) ** 2)


class QuantisedOccupationMC:
    """Monte-Carlo ``Var{E(Q(Theta) | Y_S)}`` for the occupation label.

    ``Z = Z_Q + Z_P`` with ``Z_Q ~ N(0, Q_S)`` the posterior mean given ``Y_S``
    and ``Z_P ~ N(0, P_S)`` independent, so the conditional expectation is an
    average over ``Z_P`` at fixed ``Z_Q``.  Two independent inner half-batches
    give an unbiased estimate of the *variance* of the conditional expectation
    (a single batch would inflate it by the inner Monte-Carlo variance).  All
    protocols reuse the same standard normals (common random numbers), so
    differences between protocols -- which is what design regret measures -- are
    far more accurate than the individual levels.
    """

    def __init__(self, K: Array, label: LabelFunctional, seed: int):
        rng = np.random.default_rng(seed)
        self.K = K
        self.label = label
        self.c = float(getattr(label, "c", 0.0))
        self.G_out = rng.standard_normal((MC_OUT, P_GRID))
        self.G_in = rng.standard_normal((2 * MC_IN_HALF, P_GRID))
        self.cache: dict[tuple[int, ...], float] = {}

    @staticmethod
    def _factor(S: Array) -> Array:
        vals, vecs = np.linalg.eigh(0.5 * (S + S.T))
        return vecs * np.sqrt(np.maximum(vals, 0.0))

    def explained(self, key: tuple[int, ...]) -> float:
        if key in self.cache:
            return self.cache[key]
        A, R = PROTO_MATS[PROTO_INDEX[key]]
        Q = explained_covariance(self.K, A, R)
        Zq = self.G_out @ self._factor(Q).T
        Zp = self.G_in @ self._factor(self.K - Q).T
        m1 = np.empty(MC_OUT)
        m2 = np.empty(MC_OUT)
        step = 128
        for s in range(0, MC_OUT, step):
            blk = Zq[s:s + step]
            theta = ((blk[:, None, :] + Zp[None, :, :]) > self.c) @ OMEGA
            q = np.round(theta / 0.25) * 0.25
            m1[s:s + step] = q[:, :MC_IN_HALF].mean(axis=1)
            m2[s:s + step] = q[:, MC_IN_HALF:].mean(axis=1)
        val = float(np.mean(m1 * m2) - np.mean(m1) * np.mean(m2))
        self.cache[key] = val
        return val


