def mixture_protocol_explained(arm: Arm, label: LabelFunctional, A: Array,
                               R: Array, n_per_component: int) -> float:
    r"""Full-mixture ``Var{E(Theta | Y_S)}`` by deterministic Sobol integration.

    The component index is latent. For every integration point, posterior
    component weights are proportional to ``w_q p_q(y)`` and multiply the
    component-specific conditional target mean. This is not an average of
    component-specific protocol values.
    """
    d = A.shape[0]
    power = int(np.log2(n_per_component))
    if 2**power != n_per_component:
        raise ValueError("n_per_component must be a power of two")
    u = qmc.Sobol(d, scramble=True, seed=SEED + 31 * d).random_base2(power)
    G = norm.ppf(np.clip(u, 1e-12, 1.0 - 1e-12))
    probs = np.array([p for p, _ in arm.nodes], dtype=float)
    probs /= probs.sum()

    comp = []
    y_blocks = []
    for _, K in arm.nodes:
        M = A @ K @ A.T + R
        chol = np.linalg.cholesky(M)
        inv = np.linalg.inv(M)
        sign, logdet = np.linalg.slogdet(M)
        if sign <= 0:
            raise ValueError("mixture observation covariance is not positive definite")
        B = K @ A.T @ inv
        post_sd = np.sqrt(np.maximum(np.diag(K - B @ A @ K), 1e-12))
        comp.append((inv, float(logdet), B, post_sd))
        y_blocks.append(G @ chol.T)
    Y = np.concatenate(y_blocks, axis=0)
    outer_weight = np.repeat(probs / n_per_component, n_per_component)

    log_joint = np.empty((Y.shape[0], len(comp)))
    conditional_mean = np.empty_like(log_joint)
    for q, (inv, logdet, B, post_sd) in enumerate(comp):
        quad = np.einsum("ni,ij,nj->n", Y, inv, Y)
        log_joint[:, q] = (np.log(probs[q])
                           - 0.5 * (d * np.log(2.0 * np.pi) + logdet + quad))
        mu = Y @ B.T
        if isinstance(label, MeanLabel):
            conditional_mean[:, q] = mu @ OMEGA
        else:
            c = float(getattr(label, "c", 0.0))
            conditional_mean[:, q] = ndtr(
                (mu - c) / post_sd[None, :]) @ OMEGA
    mx = np.max(log_joint, axis=1, keepdims=True)
    posterior = np.exp(log_joint - mx)
    posterior /= posterior.sum(axis=1, keepdims=True)
    mixed_mean = np.sum(posterior * conditional_mean, axis=1)
    target_mean = 0.0 if isinstance(label, MeanLabel) else float(
        1.0 - ndtr(getattr(label, "c", 0.0)))
    return float(np.sum(outer_weight * (mixed_mean - target_mean) ** 2))


def mixture_all_explained(arm: Arm, label_name: str,
                          label: LabelFunctional) -> Array:
    """Full-posterior mixture values, with a higher-resolution near-set audit.

    Every feasible protocol is first evaluated at the publication resolution.
    The higher-resolution audit covers at least the leading 50 and every
    protocol within ``MIXTURE_QMC_NEAR_MARGIN`` of the preliminary optimum, so a
    protocol immediately outside an arbitrary top-20 cut cannot enter unseen.
    """
    coarse = np.array([
        mixture_protocol_explained(
            arm, label, A, R, MIXTURE_QMC_PER_COMPONENT)
        for A, R in PROTO_MATS
    ])
    top = np.unique(np.concatenate([
        np.argsort(coarse)[-MIXTURE_QMC_CHECK_TOP:],
        np.flatnonzero(coarse.max() - coarse <= MIXTURE_QMC_NEAR_MARGIN),
    ]))
    fine = np.array([
        mixture_protocol_explained(
            arm, label, PROTO_MATS[j][0], PROTO_MATS[j][1],
            MIXTURE_QMC_CHECK_PER_COMPONENT)
        for j in top
    ])
    discrepancy = np.abs(fine - coarse[top])
    out = coarse.copy()
    out[top] = fine
    order = np.argsort(out)
    best_gap = float(out[order[-1]] - out[order[-2]])
    max_change = float(discrepancy.max())
    outside = np.setdiff1d(np.arange(out.size), top)
    outside_upper = (float(np.max(coarse[outside]) + max_change)
                     if outside.size else float("-inf"))
    outside_margin = float(out[order[-1]] - outside_upper)
    MIXTURE_NUMERICS[label_name] = {
        "posterior_formula": "sum_q w_q p_q(y) E_q(Theta|y) / sum_q w_q p_q(y)",
        "base_sobol_points_per_component": MIXTURE_QMC_PER_COMPONENT,
        "check_sobol_points_per_component": MIXTURE_QMC_CHECK_PER_COMPONENT,
        "n_feasible_protocols_evaluated_at_base_resolution": int(coarse.size),
        "near_set_margin": MIXTURE_QMC_NEAR_MARGIN,
        "n_checked_high_resolution_protocols": int(top.size),
        "max_abs_checked_protocol_change": max_change,
        "best_minus_second_best_at_final_resolution": best_gap,
        "twice_max_abs_checked_protocol_change": 2.0 * max_change,
        "best_minus_error_inflated_best_outside_check_set": outside_margin,
        "best_index": int(order[-1]),
    }
    # A one-component mixture must reduce to the analytic Gaussian value.
    check_arm = Arm("one_component_check", "check", "check",
                    [(1.0, arm.nodes[N_TAU_NODES // 2][1])])
    check_A, check_R = PROTO_MATS[35]
    check_qmc = mixture_protocol_explained(
        check_arm, label, check_A, check_R, 16384)
    check_exact = explained_variance(
        label, check_arm.nodes[0][1], check_A, check_R, OMEGA)
    MIXTURE_NUMERICS[label_name]["one_component_analytic_abs_error"] = float(
        abs(check_qmc - check_exact))
    return out


def build_truth(arm: Arm, label_name: str, label: LabelFunctional,
                rng: np.random.Generator) -> Truth:
    """True ceiling of every feasible protocol, and the true optimum."""
    F = np.zeros(len(PROTOCOLS))
    V = 0.0
    for p, K in arm.nodes:
        F += p * all_explained(label, K)
        V += p * label_variance(label, K, OMEGA)

    if arm.key == "subject_kernels":
        F = mixture_all_explained(arm, label_name, label)

    pool: list[tuple[int, ...]] | None = None
    if arm.label_mode == "clean":
        I = F / V
    elif arm.label_mode == "additive":
        # Var(Theta + xi) = V + s2 while Var{E(Theta + xi | Y)} = Var{E(Theta | Y)},
        # so the ceiling is deflated by exactly the label reliability and the
        # design problem (argmax of F) is untouched.
        V = V * (1.0 + LABEL_NOISE_FRAC)
        I = F / V
    else:                                                   # quantised label
        K = arm.nodes[0][1]
        V_clean = V
        V = quantised_var_total(V_clean, label_name, rng, K, label)
        if label_name == "mean":
            base = quantised_mean_stats(V_clean, F, 120) / V
            fine = quantised_mean_stats(V_clean, F, 640) / V
            QUANTISED_MEAN_NUMERICS.update({
                "base_gauss_hermite_nodes": 120,
                "check_gauss_hermite_nodes": 640,
                "max_abs_protocol_value_change": float(
                    np.max(np.abs(fine - base))),
            })
            I = fine
        else:
            mc1 = QuantisedOccupationMC(K, label, SEED + 991)
            mc2 = QuantisedOccupationMC(K, label, SEED + 1991)
            ARM_MC[(arm.key, label_name)] = (mc1, mc2)
            pool = [PROTOCOLS[i] for i in np.argsort(F)[::-1][:20]]
            if PROTOCOLS[REFERENCE] not in pool:
                pool.append(PROTOCOLS[REFERENCE])
            I = np.full(len(PROTOCOLS), np.nan)
            repeat_diffs = []
            for key in pool:
                v1 = mc1.explained(key) / V
                v2 = mc2.explained(key) / V
                I[PROTO_INDEX[key]] = 0.5 * (v1 + v2)
                repeat_diffs.append(abs(v1 - v2))
            QUANTISED_OCCUPATION_NUMERICS.update({
                "independent_repetitions": 2,
                "n_protocols_repeated": len(pool),
                "max_abs_protocol_value_difference": float(max(repeat_diffs)),
                "median_abs_protocol_value_difference": float(np.median(repeat_diffs)),
            })

    if pool is None:
        j = int(np.nanargmax(I))
    else:
        j = PROTO_INDEX[max(pool, key=lambda k: I[PROTO_INDEX[k]])]
    return Truth(I, PROTOCOLS[j], float(I[j]), float(V), pool)


def true_ceiling(arm: Arm, label_name: str, truth: Truth,
                 key: tuple[int, ...]) -> float:
    """True ceiling of an arbitrary protocol (Monte-Carlo on demand if needed)."""
    val = truth.I_all[PROTO_INDEX[key]]
    if np.isfinite(val):
        return float(val)
    mc1, mc2 = ARM_MC[(arm.key, label_name)]
    val = 0.5 * (mc1.explained(key) + mc2.explained(key)) / truth.var_label
    truth.I_all[PROTO_INDEX[key]] = val
    return float(val)


# --------------------------------------------------------------------------
# Downstream ridge predictor
# --------------------------------------------------------------------------
def downstream_r2(arm: Arm, label: LabelFunctional, label_name: str,
                  Z: Array, keys: Sequence[tuple[int, ...]],
                  var_clean: float, rng: np.random.Generator) -> list[float]:
    theta = label.apply(Z) @ OMEGA
    if arm.label_mode == "additive":
        theta = theta + rng.normal(0.0, np.sqrt(LABEL_NOISE_FRAC * var_clean), theta.size)
    elif arm.label_mode == "quantised":
        theta = quantise(theta, label_name, var_clean)
    out = []
    for key in keys:
        A, R = PROTO_MATS[PROTO_INDEX[key]]
        Y = Z @ A.T + rng.standard_normal((Z.shape[0], A.shape[0])) * np.sqrt(np.diag(R))
        pred = LEARNERS["ridge"](Y[:N_TRAIN], theta[:N_TRAIN], Y[N_TRAIN:],
                                 rng=np.random.default_rng(0))
        out.append(r2_score(theta[N_TRAIN:], pred))
    return out


# --------------------------------------------------------------------------
# Main loop
# --------------------------------------------------------------------------
def run() -> tuple[list[dict], dict]:
    rows: list[dict] = []
    truths: dict[tuple[str, str], Truth] = {}
    var_clean: dict[tuple[str, str], float] = {}

    with Timer("S6 truth tables"):
        for arm in ARMS:
            for lname, lab in LABELS.items():
                var_clean[(arm.key, lname)] = float(
                    sum(p * label_variance(lab, K, OMEGA) for p, K in arm.nodes))
                truths[(arm.key, lname)] = build_truth(
                    arm, lname, lab, np.random.default_rng(SEED + 77))
                t = truths[(arm.key, lname)]
                print(f"  {arm.key:22s} {lname:11s} I* = {t.I_star:.4f}"
                      f"  S* = {[CANDIDATES[i].tag for i in t.star]}")

    with Timer("S6 replications"):
        for ai, arm in enumerate(ARMS):
            t_arm = time.perf_counter()
            for rep in range(N_REP):
                rng = np.random.default_rng(SEED + 10_000 * (ai + 1) + rep)
                W, mask = arm.calibration(rng)
                K_fit, tau_hat = fit_K(W, mask, arm.rank_normalise)
                Z = arm.sample_latent(rng, N_TRAIN + N_TEST)

                for lname, lab in LABELS.items():
                    truth = truths[(arm.key, lname)]
                    Vc = var_clean[(arm.key, lname)]
                    V_fit = label_variance(lab, K_fit, OMEGA)
                    F_fit = all_explained(lab, K_fit)
                    I_fit_all = F_fit / V_fit

                    greedy = select_protocol_greedy(lab, K_fit, grid, CANDIDATES,
                                                    budget=BUDGET, cost_aware=True,
                                                    local_search=True)
                    key_g = protocol_key(greedy.actions)
                    key_e = PROTOCOLS[int(np.argmax(F_fit))]
                    key_r = PROTOCOLS[REFERENCE]

                    I_true_g = true_ceiling(arm, lname, truth, key_g)
                    I_true_e = true_ceiling(arm, lname, truth, key_e)
                    I_true_r = true_ceiling(arm, lname, truth, key_r)

                    finite = np.isfinite(truth.I_all)
                    unif = (float(np.max(np.abs(I_fit_all[finite] - truth.I_all[finite])))
                            if truth.pool is None else float("nan"))

                    r2s = downstream_r2(arm, lab, lname, Z, [key_g, truth.star], Vc, rng)

                    rows.append({
                        "arm": arm.key, "display": arm.display, "group": arm.group,
                        "label": lname, "rep": rep, "tau_hat": tau_hat,
                        "I_fit_selected": float(I_fit_all[PROTO_INDEX[key_g]]),
                        "I_true_selected": I_true_g,
                        "I_fit_reference": float(I_fit_all[REFERENCE]),
                        "I_true_reference": I_true_r,
                        "I_true_star": truth.I_star,
                        "ceiling_error_selected": abs(
                            float(I_fit_all[PROTO_INDEX[key_g]]) - I_true_g),
                        "ceiling_error_reference": abs(
                            float(I_fit_all[REFERENCE]) - I_true_r),
                        "ceiling_error_uniform": unif,
                        "ceiling_signed_selected":
                            float(I_fit_all[PROTO_INDEX[key_g]]) - I_true_g,
                        "design_regret": truth.I_star - I_true_g,
                        "design_regret_exhaustive": truth.I_star - I_true_e,
                        "ridge_r2_selected": r2s[0],
                        "ridge_r2_oracle": r2s[1],
                        "ridge_loss_selected": 1.0 - r2s[0],
                        "ridge_regret": r2s[1] - r2s[0],
                        "protocol_selected": "+".join(CANDIDATES[i].tag for i in key_g),
                        "protocol_star": "+".join(CANDIDATES[i].tag for i in truth.star),
                    })
            print(f"  [{ai + 1:2d}/{len(ARMS)}] {arm.key:22s} "
                  f"{time.perf_counter() - t_arm:5.1f}s")
    return rows, {k: v for k, v in truths.items()}


