def lag_profile(C: Array) -> Array:
    """Average the correlation matrix along its diagonals (stationarity)."""
    return np.array([np.nanmean(np.diag(C, k)) for k in range(C.shape[0])])


def fit_ou_tau(C: Array, lag_frac: float = 0.5) -> float:
    """Least-squares integral time of an OU fit to the empirical lag profile."""
    rho = lag_profile(C)
    lags = np.arange(rho.size) * grid.dt
    keep = (lags <= lag_frac * grid.horizon) & np.isfinite(rho)
    u, r = lags[keep], rho[keep]

    def loss(log_tau: float) -> float:
        return float(np.sum((r - np.exp(-u / np.exp(log_tau))) ** 2))

    res = minimize_scalar(loss, bounds=(np.log(0.02), np.log(500.0)), method="bounded")
    return float(np.exp(res.x))


def K_from_tau(tau: float) -> Array:
    return kernel_matrix(grid, make_kernel("ou", tau=float(tau)))


def rank_normal_scores(W: Array) -> Array:
    """Column-wise van der Waerden scores: the marginal-free copula estimate."""
    m = W.shape[0]
    ranks = np.argsort(np.argsort(W, axis=0), axis=0) + 1.0
    return norm.ppf((ranks - 0.5) / m)


def pairwise_complete_corr(W: Array, mask: Array) -> Array:
    """Pairwise-complete Pearson correlation -- the standard MAR-valid recipe."""
    O = mask.astype(float)
    X = W * O
    n = O.T @ O
    ok = n >= 5
    n_safe = np.maximum(n, 1.0)
    Sj = X.T @ O
    Sjj = (X * X).T @ O
    Sjl = X.T @ X
    mj = Sj / n_safe
    ml = mj.T
    cov = Sjl / n_safe - mj * ml
    vj = np.maximum(Sjj / n_safe - mj**2, 1e-12)
    vl = vj.T
    C = cov / np.sqrt(vj * vl)
    C = np.where(ok, C, np.nan)
    C = 0.5 * (C + C.T)
    np.fill_diagonal(C, 1.0)
    return np.clip(C, -1.0, 1.0)


def fit_K(W: Array, mask: Array | None, rank_normalise: bool) -> tuple[Array, float]:
    if rank_normalise:
        W = rank_normal_scores(W)
    C = np.corrcoef(W, rowvar=False) if mask is None else pairwise_complete_corr(W, mask)
    tau_hat = fit_ou_tau(C)
    return K_from_tau(tau_hat), tau_hat


