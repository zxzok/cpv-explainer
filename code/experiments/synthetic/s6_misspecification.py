CANDIDATE_TIMES = (0.5, 4.0, 8.0, 12.0, 15.0, 17.0, 18.5, 19.75)


def build_candidates() -> list[Action]:
    """Eight admissible occasions plus replicated occasions that cost ``M`` units.

    Two deliberate features make the design problem informative.

    *Irregular times.*  Admissible occasions are not equally spaced -- they get
    denser towards the end of the horizon, as clinic visits and study contacts
    do.  With equally spaced times and a stationary kernel the problem is
    translation symmetric and *every* model returns the same placement, so
    design regret would be identically zero for reasons unrelated to
    misspecification.  With irregular times the optimum trades "one more distant
    occasion" against "one more occasion inside the recency window", and which
    side wins depends on the correlation time.

    *Replicated occasions.*  ``M = 2`` and ``M = 4`` actions on two of those
    times cost ``M`` budget units and divide the noise by ``M`` exactly, giving
    the distinct-occasions versus repeated-segments trade-off of the paper.
    """
    acts = [Action(time=float(t), width=0.0, n_segments=1, noise=NU2, cost=1.0,
                   tag=f"t{t:.2f}") for t in CANDIDATE_TIMES]
    for m in (2, 4):
        for t in (CANDIDATE_TIMES[-3], CANDIDATE_TIMES[-1]):
            acts.append(Action(time=float(t), width=0.0, n_segments=m, noise=NU2,
                               cost=float(m), tag=f"t{t:.2f}xM{m}"))
    return acts


