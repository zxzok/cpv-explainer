@dataclass
class Arm:
    key: str
    display: str
    group: str
    nodes: list[tuple[float, Array]]          # (probability, true kernel)
    link: Callable[[Array], Array] | None = None
    rank_normalise: bool = False
    mnar: bool = False
    label_mode: str = "clean"                 # clean | additive | quantised
    _chol: list[Array] = field(default_factory=list, repr=False)

    def cholesky(self) -> list[Array]:
        if not self._chol:
            self._chol = [np.linalg.cholesky(K + 1e-10 * np.eye(P_GRID))
                          for _, K in self.nodes]
        return self._chol

    def sample_latent(self, rng: np.random.Generator, n: int) -> Array:
        """Draw ``n`` latent trajectories from the (possibly mixed) true model."""
        probs = np.array([p for p, _ in self.nodes])
        chols = self.cholesky()
        if len(chols) == 1:
            return rng.standard_normal((n, P_GRID)) @ chols[0].T
        which = rng.choice(len(chols), size=n, p=probs / probs.sum())
        Z = np.empty((n, P_GRID))
        for q in range(len(chols)):
            sel = which == q
            k = int(sel.sum())
            if k:
                Z[sel] = rng.standard_normal((k, P_GRID)) @ chols[q].T
        return Z

    def calibration(self, rng: np.random.Generator) -> tuple[Array, Array | None]:
        """What the analyst actually sees: ``m`` dense calibration trajectories."""
        Z = self.sample_latent(rng, M_CALIB)
        mask = None
        if self.mnar:                      # drop observations at high latent state
            mask = Z <= MNAR_CUT
            Z = np.where(mask, Z, 0.0)
        W = Z if self.link is None else self.link(Z)
        return W, mask


def lognormal_tau_nodes() -> list[tuple[float, float]]:
    """Gauss--Hermite discretisation of ``tau_i ~ LogNormal`` with ``E tau = TAU_TRUE``."""
    x, w = roots_hermitenorm(N_TAU_NODES)
    probs = w / np.sqrt(2.0 * np.pi)
    probs = probs / probs.sum()
    mu = np.log(TAU_TRUE) - 0.5 * TAU_SDLOG**2
    taus = np.exp(mu + TAU_SDLOG * x)
    return list(zip(probs.tolist(), taus.tolist()))


