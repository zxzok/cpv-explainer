# Marginal links (Gaussian copula, wrong marginals)
# --------------------------------------------------------------------------
_Z_TAB = np.linspace(-8.5, 8.5, 40001)
_T4_TAB = student_t.ppf(np.clip(ndtr(_Z_TAB), 1e-15, 1 - 1e-15), T_DF)


def link_lognormal(Z: Array) -> Array:
    mean = np.exp(0.5 * LOGNORM_SIGMA**2)
    sd = np.sqrt(np.exp(2.0 * LOGNORM_SIGMA**2)
                 - np.exp(LOGNORM_SIGMA**2))
    return (np.exp(LOGNORM_SIGMA * Z) - mean) / sd


def link_student_t(Z: Array) -> Array:
    return np.interp(Z, _Z_TAB, _T4_TAB) / np.sqrt(T_DF / (T_DF - 2.0))


