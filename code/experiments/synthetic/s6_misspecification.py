    def pick(arm: str, field_: str) -> float:
        return float(np.mean([s[f"{field_}_mean"] for s in summary if s["arm"] == arm]))

    ctrl_ce = pick("control", "ceiling_error_selected")
    ctrl_dr = pick("control", "design_regret")
    # "Near the control" needs a scale.  A design regret is called damaging only
    # if it exceeds the control by at least 1% of the control ceiling -- anything
    # smaller is inside the finite-m noise of the correctly specified pipeline.
    ctrl_I = pick("control", "I_true_star")
    dr_tol = ctrl_dr + 0.01 * ctrl_I
    ce_tol = 2.0 * ctrl_ce
    benign_design = [a.key for a in ARMS
                     if a.key != "control" and pick(a.key, "design_regret") <= dr_tol]
    damaging_design = [a.key for a in ARMS
                       if a.key != "control" and pick(a.key, "design_regret") > dr_tol]
    benign_ceiling = [a.key for a in ARMS
                      if a.key != "control"
                      and pick(a.key, "ceiling_error_selected") <= ce_tol]
    damaging_ceiling = [a.key for a in ARMS
                        if a.key != "control"
                        and pick(a.key, "ceiling_error_selected") > ce_tol]
    # Arms whose *reported* ceiling exceeds the truth: the analyst over-promises.
    optimistic = [a.key for a in ARMS
                  if pick(a.key, "ceiling_signed_selected") > ce_tol]
    pessimistic = [a.key for a in ARMS
                   if pick(a.key, "ceiling_signed_selected") < -ce_tol]

