_SCI = re.compile(r"^(-?)(\d(?:\.\d+)?)e([+-])0*(\d+)$")


def _latexify(body: str) -> str:
    """Render 1e-16 as a proper LaTeX power of ten rather than literal 'e-16'."""
    m = _SCI.match(body)
    if not m:
        return body
    sign, mant, esign, exp = m.groups()
    expo = ("-" if esign == "-" else "") + exp
    if mant in ("1", "1.0"):
        return f"${sign}10^{{{expo}}}$"
    return f"${sign}{mant}\\times10^{{{expo}}}$"


def _round_away(value: float, fmt: str, up: bool) -> float:
    """Round to the printed precision, away from the claim rather than to nearest.

    A macro quoted as "at most X" must not print a value the data exceeds: a
    maximum 0.007821 formatted "{:.4f}" to nearest gives 0.0078, and "at most
    0.0078" is then false.  ``up`` rounds a stated upper bound up and a stated
    lower bound down, so the sentence stays true at the printed digits.
    """
    m = re.search(r"\.(\d+)f", fmt)
    if not m:
        return value
    q = 10 ** int(m.group(1))
    scaled = value * q
    return (math.ceil(scaled) if up else math.floor(scaled)) / q


def emit(macro: str, value, fmt: str = "{:.3f}", bound: str | None = None) -> None:
    """``bound="upper"``/``"lower"`` rounds away from the claim (see _round_away)."""
    if value is None:
        missing.append(macro)
        body = r"\textbf{??}"
    elif isinstance(value, str):
        body = value
    else:
        try:
            if bound in ("upper", "lower") and isinstance(value, (int, float)):
                value = _round_away(float(value), fmt, bound == "upper")
            body = _latexify(fmt.format(value))
        except (ValueError, TypeError):
            body = str(value)
    lines.append(rf"\newcommand{{\{macro}}}{{{body}}}")


