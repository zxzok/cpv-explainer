    _rows = list(_csv.DictReader(open(_mis)))
    _by = {}
    for _r in _rows:
        _by.setdefault(_r["arm"], []).append(_r)
    def _mean(arm, field):
        rs = _by.get(arm, [])
        vs = [float(r[field]) for r in rs if r.get(field) not in (None, "", "nan")]
        return sum(vs) / len(vs) if vs else None
    def _sd(arm, field):
        """SD of the per-replication mean over the two targets."""
        rs = _by.get(arm, [])
        per_rep = {}
        for r in rs:
            v = r.get(field)
            if v in (None, "", "nan"):
                continue
            per_rep.setdefault(r["rep"], []).append(float(v))
        vals = [sum(v) / len(v) for v in per_rep.values()]
        if len(vals) < 2:
            return None
        m = sum(vals) / len(vals)
        return (sum((x - m) ** 2 for x in vals) / (len(vals) - 1)) ** 0.5
    emit("numMisReps", len({r["rep"] for r in _rows}) if _rows else None, "{:d}")
